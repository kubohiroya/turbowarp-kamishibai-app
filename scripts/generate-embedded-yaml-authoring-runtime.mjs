import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createDsl4BlockAuthoringExtensionSource} from '../dist/dsl4/structured-block-source.js';
const root = fileURLToPath(new URL('../', import.meta.url));
/** Emit a fixed owner artifact; runtime bundles must not inline registration-source generators. */
export async function generateEmbeddedYamlAuthoringRuntime() {
  // The source carries its own extension header, shared with every SB3 the builder writes.
  const source = createDsl4BlockAuthoringExtensionSource([], {
    narrativeControlEnabled: true,
    referenceViews: true,
  });
  const url = 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
  const module =
    '// Generated by scripts/generate-embedded-yaml-authoring-runtime.mjs.\n/** @type {string} */\nexport const embeddedYamlAuthoringRuntimeURL = ' +
    JSON.stringify(url) +
    ';\n';
  for (const prefix of ['src', 'dist']) {
    const file = path.join(root, prefix, 'dsl4/generated/embedded-yaml-authoring-runtime.js');
    await mkdir(path.dirname(file), {recursive: true});
    await writeFile(file, module);
  }
  return url;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await generateEmbeddedYamlAuthoringRuntime();
